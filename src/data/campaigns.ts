export const ALL_FORMATS: CampaignFormat[] = [...CAMPAIGN_FORMATS, AUDIT_FORMAT, CUSTOM_FORMAT];

export function getFormat(intent: string | null | undefined): CampaignFormat | null {
  if (!intent) return null;
  return ALL_FORMATS.find((f) => f.intent === intent) ?? null;
}

